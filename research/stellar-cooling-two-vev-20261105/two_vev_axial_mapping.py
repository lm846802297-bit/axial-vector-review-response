#!/usr/bin/env python3
"""Exact two-VEV mapping for the charge-two S / charge-one sigma completion.

Conventions:
S=(v_s+s+i a_s)/sqrt(2), Q_X(S)=+2
sigma=(v_sigma+sigma_r+i a_sigma)/sqrt(2), Q_X(sigma)=+1
D_mu=partial_mu-i g_X Q_X A'_mu.

m_A'^2 = g_X^2 (4 v_s^2 + v_sigma^2)
G = (2 v_s a_s + v_sigma a_sigma) / v_X
v_X = sqrt(4 v_s^2 + v_sigma^2)

The orthogonal physical CP-odd direction is
a_perp = (v_sigma a_s - 2 v_s a_sigma) / v_X.

The charged-lepton mass is generated by S in the VLL seesaw. In the
small-light/heavy-mixing limit its phase coupling is m_l/v_s. Projecting
a_s onto the eaten Goldstone gives |g_Gll| = 2 m_l/v_X, equal to the
longitudinal-current relation 2 |g_A| m_l / m_A' when |g_A|=|g_X|.

This module only performs the exact kinematic/Goldstone mapping. It does not
assume a scalar potential, radial mass spectrum, or scalar mixing angle.
"""
from __future__ import annotations

from dataclasses import dataclass
import math


@dataclass(frozen=True)
class TwoVEVPoint:
    v_s: float
    v_sigma: float
    g_x: float

    def __post_init__(self) -> None:
        if not all(math.isfinite(x) for x in (self.v_s, self.v_sigma, self.g_x)):
            raise ValueError("all inputs must be finite")
        if self.v_s <= 0.0 or self.v_sigma < 0.0 or self.g_x == 0.0:
            raise ValueError("require v_s > 0, v_sigma >= 0, and nonzero g_x")

    @property
    def v_x(self) -> float:
        return math.hypot(2.0 * self.v_s, self.v_sigma)

    @property
    def m_a(self) -> float:
        return abs(self.g_x) * self.v_x

    @property
    def r_sigma(self) -> float:
        return (self.v_sigma / (2.0 * self.v_s)) ** 2

    @property
    def goldstone_s_projection(self) -> float:
        return 2.0 * self.v_s / self.v_x

    def goldstone_lepton_yukawa(self, m_l: float) -> float:
        if not math.isfinite(m_l) or m_l < 0.0:
            raise ValueError("m_l must be finite and non-negative")
        return (m_l / self.v_s) * self.goldstone_s_projection

    def longitudinal_current_yukawa(self, m_l: float, g_a: float | None = None) -> float:
        if not math.isfinite(m_l) or m_l < 0.0:
            raise ValueError("m_l must be finite and non-negative")
        coupling = abs(self.g_x if g_a is None else g_a)
        return 2.0 * coupling * m_l / self.m_a

    @classmethod
    def from_mediator_inputs(cls, m_a: float, g_x: float, r_sigma: float) -> "TwoVEVPoint":
        if not all(math.isfinite(x) for x in (m_a, g_x, r_sigma)):
            raise ValueError("all inputs must be finite")
        if m_a <= 0.0 or g_x == 0.0 or r_sigma < 0.0:
            raise ValueError("require m_A' > 0, nonzero g_x, and r_sigma >= 0")
        v_s = m_a / (2.0 * abs(g_x) * math.sqrt(1.0 + r_sigma))
        v_sigma = 2.0 * v_s * math.sqrt(r_sigma)
        return cls(v_s=v_s, v_sigma=v_sigma, g_x=g_x)


def eaten_goldstone(v_s: float, v_sigma: float, a_s: float, a_sigma: float) -> float:
    v_x = math.hypot(2.0 * v_s, v_sigma)
    if v_s <= 0.0 or v_sigma < 0.0 or v_x == 0.0:
        raise ValueError("require v_s > 0 and v_sigma >= 0")
    return (2.0 * v_s * a_s + v_sigma * a_sigma) / v_x


def physical_pseudoscalar(v_s: float, v_sigma: float, a_s: float, a_sigma: float) -> float:
    v_x = math.hypot(2.0 * v_s, v_sigma)
    if v_s <= 0.0 or v_sigma < 0.0 or v_x == 0.0:
        raise ValueError("require v_s > 0 and v_sigma >= 0")
    return (v_sigma * a_s - 2.0 * v_s * a_sigma) / v_x
