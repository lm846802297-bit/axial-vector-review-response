#!/usr/bin/env python3
"""Same-Yukawa-vertex Q_LD pure-WW subgraphs: exact UV/EFT soft identity.

LD-W-03 connects barL-H at the left Yukawa vertex; LD-W-04 connects L-Hdag
at the conjugate right vertex. The heavy propagator carries only the external
channel momentum, so the W-loop denominators are entirely light. This script
checks the momentum routing, chiral heavy-propagator reduction, and the
large-loop-momentum numerator that controls the common light-loop UV pole.

It does not evaluate the full finite massless triangle or the complete Ward
sum. The matching statement is that the same light-loop form factor multiplies
the same 1/M_E^2 derivative insertion on the EFT side; the hard-region loop
integrals are scaleless because no M_E occurs in their denominators.
"""
import sympy as sp

I = sp.I
pauli = (
    sp.Matrix([[0, 1], [1, 0]]),
    sp.Matrix([[0, -I], [I, 0]]),
    sp.Matrix([[1, 0], [0, -1]]),
)
zero, eye = sp.zeros(2), sp.eye(2)
GAMMA = (
    sp.BlockMatrix([[zero, -I*pauli[0]], [I*pauli[0], zero]]).as_explicit(),
    sp.BlockMatrix([[zero, -I*pauli[1]], [I*pauli[1], zero]]).as_explicit(),
    sp.BlockMatrix([[zero, -I*pauli[2]], [I*pauli[2], zero]]).as_explicit(),
    sp.BlockMatrix([[zero, eye], [eye, zero]]).as_explicit(),
)
GAMMA5 = GAMMA[0]*GAMMA[1]*GAMMA[2]*GAMMA[3]
P_L = (sp.eye(4)-GAMMA5)/2
P_R = (sp.eye(4)+GAMMA5)/2
k = sp.symbols("k0:4")
p1 = sp.symbols("p1_0:4")
p2 = sp.symbols("p2_0:4")
p3 = sp.symbols("p3_0:4")
p4 = sp.symbols("p4_0:4")
M = sp.symbols("M", positive=True)


def dot(a,b):
    return sp.expand(sum(a[i]*b[i] for i in range(4)))


def slash(a):
    return sum((a[i]*GAMMA[i] for i in range(4)), sp.zeros(4))


def add(a,b):
    return [sp.expand(a[i]+b[i]) for i in range(4)]


def scale(c,a):
    return [sp.expand(c*a[i]) for i in range(4)]


def same_vertex_data():
    P = add(p1,p2)
    Q = add(p3,p4)
    # W momentum k; light propagators are (k+p1)^2 and (k-p2)^2
    # on the left Yukawa vertex, and (k+p4)^2 and (k-p3)^2 on the right.
    D03 = (dot(k,k), dot(add(k,p1),add(k,p1)), dot([k[i]-p2[i] for i in range(4)],[k[i]-p2[i] for i in range(4)]))
    D04 = (dot(k,k), dot(add(k,p4),add(k,p4)), dot([k[i]-p3[i] for i in range(4)],[k[i]-p3[i] for i in range(4)]))

    # Stripped numerator chains; overall Feynman-rule phases are common and omitted.
    N03 = sp.zeros(4)
    N04 = sp.zeros(4)
    for mu in range(4):
        N03 += GAMMA[mu]*slash(add(k,p1))*(2*p2[mu]-k[mu])
        N04 += (2*p3[mu]-k[mu])*slash(add(k,p4))*GAMMA[mu]

    # The leading large-k term is obtained by setting external momenta to zero.
    zero_ext = {x:0 for x in (*p1,*p2,*p3,*p4)}
    N03_hard = N03.applyfunc(lambda e: sp.expand(e.subs(zero_ext)))
    N04_hard = N04.applyfunc(lambda e: sp.expand(e.subs(zero_ext)))
    k2 = dot(k,k)
    expected = -k2*sp.eye(4)

    # The chirality-preserving heavy propagator has no mass numerator:
    # P_R (slash(P)+M) P_L = slash(P) P_L.
    Pslash = slash(P)
    heavy_projected = P_R*(Pslash+M*sp.eye(4))*P_L
    expected_heavy = Pslash*P_L

    # The EFT derivative momentum is q_D=p3+p4=-P.
    qD = Q
    momentum_conservation = {
        p4[i]: -p1[i]-p2[i]-p3[i] for i in range(4)
    }
    qD_conserved = [sp.expand(component.subs(momentum_conservation)) for component in qD]
    return {
        "P": P,
        "Q": Q,
        "D03": D03,
        "D04": D04,
        "N03_hard": N03_hard,
        "N04_hard": N04_hard,
        "expected_numerator": expected,
        "heavy_projected": heavy_projected,
        "expected_heavy": expected_heavy,
        "qD": qD,
        "qD_conserved": qD_conserved,
    }


def main():
    data = same_vertex_data()
    assert sp.simplify(data["N03_hard"]-data["expected_numerator"]) == sp.zeros(4)
    assert sp.simplify(data["N04_hard"]-data["expected_numerator"]) == sp.zeros(4)
    assert sp.simplify(data["heavy_projected"]-data["expected_heavy"]) == sp.zeros(4)
    assert sp.simplify(
        sp.Matrix(data["qD_conserved"])+sp.Matrix(data["P"])
    ) == sp.zeros(4,1)

    print("RC-001 same-vertex Q_LD pure-WW soft identity")
    print("LD-W-03 denominators: k^2, (k+p1)^2, (k-p2)^2")
    print("LD-W-04 denominators: k^2, (k+p4)^2, (k-p3)^2")
    print("PASS: both stripped numerator chains have leading term -k^2 * identity.")
    print("PASS: P_R (slash(P)+M_E) P_L = slash(P) P_L; the mass numerator vanishes.")
    print("PASS: q_D=p3+p4=-(p1+p2)=-P.")
    print("Matching: the heavy propagator is independent of the W-loop momentum.")
    print("  Its leading term is -slash(P)/M_E^2, exactly the Q_LD derivative insertion.")
    print("  The same light triangle therefore appears on both sides of UV-EFT matching.")
    print("  The hard-region loop integrals contain no M_E scale and are scaleless in DR.")
    print("  No finite O(g2^2/M_E^2) hard coefficient is generated by LD-W-03/04.")
    print("BOUNDARY: full finite triangle, common counterterms, external legs and Ward sum remain open.")


if __name__ == "__main__":
    main()
