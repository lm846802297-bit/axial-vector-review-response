#!/usr/bin/env python3
"""Soft-insertion audit for Q_LD^(8) and Q_RD^(8).

Scope: unbroken, massless EFT; one insertion; zero external fermions;
two external scalar legs; no gauge-boson attachments. The fermion loop is
the coincident-point tadpole generated by closing the bilinear in
(bar psi Phi) (i Dslash)^3 (Phi^dagger psi).

The calculation checks the numerator reduction and shows that every term
is a scaleless DR vacuum integral. It does NOT claim that gauge-corrected
fermionic/current amplitudes vanish.
"""
import sympy as sp

K, a, p2, d = sp.symbols("K a p2 d", nonzero=True)
# (k+p)^2 (k+p).k / k^2, from Tr[(slash(k+p))^3 slash(k)]/k^2
integrand = sp.cancel((K + 2*a + p2)*(K + a)/K)
expanded = sp.expand(integrand)
expected = K + 3*a + 2*a**2/K + p2 + p2*a/K
assert sp.simplify(expanded-expected) == 0

# Symmetric integration:
# int a = int (k.p) = 0;
# int a^2/K = p^2/d int 1;
# int K, int 1 are all scaleless vacuum integrals.
angular_reduced = K + 2*p2/d + p2
assert sp.simplify(
    angular_reduced - (K + 2*a**2/K + p2).subs(a**2/K,p2/d)
) == 0

# All remaining radial integrals are scaleless in dimensional regularization.
scaleless_basis = {"int_dk_1", "int_dk_k2"}
assert len(scaleless_basis) == 2

# Formal inverse-mass counting: Q8 coefficient is M^-4. Any mass insertion
# generated by C5 carries at least one additional M^-1 in the unbroken EFT.
M = sp.symbols("M", positive=True)
q8_order = M**-4
c5_mass_insertion_order = q8_order*M**-1
assert sp.simplify(c5_mass_insertion_order-M**-5) == 0

print("PASS 1: the one-insertion Q8 fermion tadpole numerator reduces to K + 3(k.p) + 2(k.p)^2/K + p^2 + p^2(k.p)/K")
print("PASS 2: odd terms vanish and tensor reduction gives only scaleless integrals int 1 and int k^2")
print("PASS 3: the pure massless unbroken-phase one-insertion tadpole vanishes in dimensional regularization")
print("PASS 4: adding a C5-induced light-fermion mass insertion raises the formal order to at least M_E^-5")
print("SCOPE: pure scalar two-point/tadpole projection, one Q_LD^(8) or Q_RD^(8) insertion, no gauge attachments")
print("OPEN: O(g^2/M_E^4) gauge-corrected fermionic/current amplitudes, covariant-derivative contact terms, EOM/source reduction, and UV hard partners")
