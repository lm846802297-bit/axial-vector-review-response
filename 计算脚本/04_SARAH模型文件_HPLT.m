(* 建议：直接从 SARAH 自带的 SM（非 SUSY）复制，然后做以下修改：      *)
(*   1) 增加第 4 个规范群 U(1)_X                                   *)
(*   2) 增加矢量样轻子 EE 与复单态 Sg                               *)
(*   3) 按下面的电荷指派设 X                                        *)

Model`Name        = "HPLT";
Model`NameLaTeX   = "Higgs-Portal axial $L_\\mu-L_\\tau$";
Model`Authors     = "...";
Model`Date        = "2026-01-01";

(* ------------------------------------------------------------ *)
(*  规范群                                                        *)
(*  {Name, Group, Coupling, CouplingName, GUTnormalized?}         *)
(* ------------------------------------------------------------ *)

Gauge[[1]] = {B,   U[1],  hypercharge, g1, False};
Gauge[[2]] = {WB,  SU[2], left,        g2, True };
Gauge[[3]] = {G,   SU[3], color,       g3, False};
Gauge[[4]] = {X,   U[1],  xcharge,     gX, False};   (* 新增 U(1)_X *)

(* ------------------------------------------------------------ *)
(*  费米子                                                        *)
(*  语法：{Name, 代数, 分量, Y, SU(2)维数, SU(3)维数, X电荷列表}     *)
(* ------------------------------------------------------------ *)

(* 轻子二重态：X = {0, +1, -1} 对应 {e, mu, tau} *)
FermionFields[[1]] = {LL, 3, {vL, eL}, -1/2, 2, 1, { 0, +1, -1}};

(* 右手带电轻子：mu_R = -1（与 L_mu=+1 反号 => 轴向）*)
FermionFields[[2]] = {lR, 3,  lR,       -1,   1, 1, { 0, -1, +1}};

(* 矢量样轻子：SU(2) 单态, Y=-1, 左右手 X 电荷**相同** *)
(*   E_mu = +1, E_tau = -1                                        *)
FermionFields[[3]] = {EE, 2,  EE,       -1,   1, 1, {    +1, -1}};

(* ------------------------------------------------------------ *)
(*  标量                                                          *)
(* ------------------------------------------------------------ *)

ScalarFields[[1]] = {H,  1, {Hp, H0},  1/2, 2, 1, 0};   (* Higgs, X=0 *)
ScalarFields[[2]] = {Sg, 1,  Ss,        0,  1, 1, 2};    (* 单态, X=+2 *)

(* ------------------------------------------------------------ *)
(*  相互作用（非 SUSY 写法）                                       *)
(* ------------------------------------------------------------ *)

(* 允许的项（X 守恒）：                                            *)
(*   y1: LL.H.EE    X = -1 + 0 + 1 = 0   ✓                        *)
(*   y2: EE.lR.Sg   X = -1 - 1 + 2 = 0   ✓                        *)
(* 禁戒的项（X 不守恒，SARAH 会报错）：                             *)
(*   LL.H.lR        X = -1 + 0 - 1 = -2  ✗   <- 直接 Dirac 质量被禁戒 *)
(*   H.Sg           X =  0 + 2     = +2  ✗                        *)
(*   H.Sg.Sg        X =  0 + 4     = +4  ✗                        *)
(*   => 唯一允许的可重整 portal 是 |H|^2 |S|^2 （X=0）              *)

SuperPotential = - y1 LL.H.EE - y2 EE.lR.Sg
                 - MuH2 H.H - MuS2 Sg.Sg;

(* ------------------------------------------------------------ *)
(*  让 SPheno 输出圈修正质量矩阵                                   *)
(* ------------------------------------------------------------ *)

OnlyLowEnergySPheno = True;

(* 在 Les Houches 输入文件（LesHouches.in）中设置：                 *)
